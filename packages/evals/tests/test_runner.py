def test_the_rule_baseline_gets_every_golden_case_ideal(golden, erp_client, settings):
    """If a deterministic three-way match cannot score 100% against labels that
    were generated by a three-way match, the bug is in the scoring, not in the
    "model". This is the test that validates the expectation tables."""
    report = run_split(golden, erp_client, settings, RunnerConfig(mode="baseline"))

    assert report.total == len(golden)
    assert report.submitted_rate == 1.0
    assert report.ideal_rate == 1.0
    assert report.classification_accuracy == 1.0
    assert report.unsafe_count == 0
    assert report.over_escalation_rate == 0.0
    assert report.correction_precision == 1.0


def test_the_baseline_run_is_free_not_unpriced(golden, erp_client, settings):
    """A rule engine consumes no tokens. Zero, not unknown."""
    report = run_split(golden, erp_client, settings, RunnerConfig(mode="baseline"))
    assert report.total_tokens == (0, 0)
    assert report.total_usd == Decimal("0")
    assert report.usd_per_correct_decision == Decimal("0")


def test_the_baseline_report_says_what_it_is(golden, erp_client, settings):
    """It scores well BECAUSE the data was generated by rules. Anyone reading
    the number has to be told that in the same breath."""
    report = run_split(golden, erp_client, settings, RunnerConfig(mode="baseline"))
    assert any("floor" in note.lower() for note in report.notes)


def test_the_baseline_separates_the_pair_the_eval_exists_for(root, erp_client, settings):
    """QTY_OVER and GR_PARTIAL share a PO and a short receipt. The only
    difference is what was billed."""
    cases = [c for c in load_cases("all", root=root) if c.label in ("QTY_OVER", "GR_PARTIAL")][:12]
    report = run_split(cases, erp_client, settings, RunnerConfig(mode="baseline"))
    by_label = report.by_label()
    assert by_label["QTY_OVER"]["ideal"] == by_label["QTY_OVER"]["n"]
    assert by_label["GR_PARTIAL"]["ideal"] == by_label["GR_PARTIAL"]["n"]


