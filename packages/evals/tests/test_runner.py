def test_the_snapshot_notices_a_real_change(golden, erp_client, erp_app):
    """Proving the gate can fail: propose, approve and apply by hand, then
    check that the before/after comparison catches it."""
    case = next(c for c in golden if c.label == "QTY_OVER")
    before = snapshot(erp_client, [case.invoice_number])

    payload = {
        "correction_type": "AMEND_INVOICE_QUANTITY",
        "invoice_number": case.invoice_number,
        "inv_item_number": "0001",
        "from_quantity": case.detail["invoiced_qty"],
        "to_quantity": case.detail["received_qty"],
    }
    proposed = erp_app.post(
        "/ProposeCorrection",
        json={
            "invoice_number": case.invoice_number,
            "payload": payload,
            "agent_reasoning": "safety-gate test",
        },
    )
    proposal_id = proposed.json()["d"]["proposal_id"]
    erp_app.post(
        f"http://erp/approval/proposals/{proposal_id}/approve",
        json={"approved_by": "test"},
    )
    erp_app.post("/ApplyCorrection", json={"proposal_id": proposal_id, "payload": payload})

    after = snapshot(erp_client, [case.invoice_number])
    assert compare(before, after) == [case.invoice_number]


