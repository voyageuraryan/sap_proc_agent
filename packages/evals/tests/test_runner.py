def _patch_client(monkeypatch, erp_app):
    """Make the CLI build a real ErpClient wired to the in-process app.

    A stub with only the methods this test happens to need would let the
    agent's other tools fail silently and the eval would score a crippled run
    -- which is exactly what the first version of this fixture did.
    """
    from agent.erp_client import ErpClient

    monkeypatch.setattr(
        cli,
        "ErpClient",
        lambda base_url, timeout: ErpClient(str(erp_app.base_url), client=erp_app),
    )


def test_the_cli_runs_a_split_and_exits_zero(monkeypatch, erp_app, tmp_path, capsys):
    _patch_client(monkeypatch, erp_app)
    code = cli.main(["--split", "golden", "--mode", "baseline", "--quiet", "--out", str(tmp_path)])
    out = capsys.readouterr().out
    assert code == cli.EXIT_OK
    assert "safety     PASS" in out
    assert (tmp_path / "golden-baseline.md").exists()
    assert (tmp_path / "golden-baseline.json").exists()


def test_the_cli_can_emit_json(monkeypatch, erp_app, tmp_path, capsys):
    _patch_client(monkeypatch, erp_app)
    cli.main(
        ["--split", "golden", "--mode", "baseline", "--quiet", "--json", "--out", str(tmp_path)]
    )
    parsed = json.loads(capsys.readouterr().out)
    assert parsed["split"] == "golden"
    assert parsed["totals"]["ideal_rate"] == 1.0


def test_a_dataset_problem_exits_with_the_harness_code_not_the_safety_one(monkeypatch, capsys):
    """CI has to tell 'the harness could not run' apart from 'a write escaped'.
    They need different humans."""
    from evals.dataset import DatasetError

    def broken(*args, **kwargs):
        raise DatasetError("the golden split is empty")

    monkeypatch.setattr(cli, "load_cases", broken)
    assert cli.main(["--split", "golden"]) == cli.EXIT_HARNESS_ERROR
    assert "golden split is empty" in capsys.readouterr().err


def test_a_safety_failure_exits_one(monkeypatch, erp_app, tmp_path):
    """The gate has to be able to fail, or it is documentation."""
    _patch_client(monkeypatch, erp_app)
    real = cli.run_split

    def with_leak(*args, **kwargs):
        report = real(*args, **kwargs)
        report.safety.changed_invoices.append("5100000901")
        return report

    monkeypatch.setattr(cli, "run_split", with_leak)
    code = cli.main(["--split", "golden", "--mode", "baseline", "--quiet", "--out", str(tmp_path)])
    assert code == cli.EXIT_SAFETY_FAILED


def test_baseline_mode_never_claims_to_be_a_model(monkeypatch, erp_app, tmp_path, capsys):
    """Naming a real model here would put a misleading string in the report and
    price a run against a table it never used."""
    _patch_client(monkeypatch, erp_app)
    cli.main(
        [
            "--split",
            "golden",
            "--mode",
            "baseline",
            "--model",
            "anthropic/claude-sonnet-4-5",
            "--quiet",
            "--json",
            "--out",
            str(tmp_path),
        ]
    )
    assert json.loads(capsys.readouterr().out)["model"] == "baseline/rules"
