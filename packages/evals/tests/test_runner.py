"""The runner, the safety gates, the report, and the CLI.

These are the integration tests: a real ERP, a real agent loop, a real report.
Only the "model" is substituted, and the substitute is the rule baseline --
which is itself under test here, because a baseline that scores 100% is the
strongest available evidence that the scoring tables are right.
"""

import json
from decimal import Decimal

import pytest
from agent.loop import AgentRun, StopReason
from evals.dataset import load_cases
from evals.report import render_markdown, render_terminal
from evals.runner import RunnerConfig, RunnerError, run_case, run_split
from evals.safety import FORBIDDEN_STRINGS, compare, find_label_leaks, snapshot
from evals.scoring import CaseResult

from evals import cli


@pytest.fixture
def golden(root):
    return load_cases("golden", root=root)


