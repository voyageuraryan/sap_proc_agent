"""A deterministic three-way-match rule engine, shaped like a model.

Every LLM eval needs a trivial baseline, and this is it. It is a LangChain
`BaseChatModel`, so it plugs into the agent graph exactly where ChatAnthropic
does; it reads prior tool results out of the message list exactly as a model
would, and emits real tool calls. The agent cannot tell the difference.

What it buys:

  * CI has something to run on day one, with no API key and no cassettes.
  * It validates the harness AND the expectation tables: a rule engine that
    encodes the same three-way match the labels were built from should score
    near-perfectly, so anything less is a bug in the scoring, not in the
    "model".
  * It is the cost and latency floor. Every dollar and every second the LLM
    spends has to buy something this does not already do.

The honest caveat, stated here rather than discovered by a reviewer: this
scores well BECAUSE the dataset was generated by rules, and this engine
encodes the same rules. That is a fact about the synthetic data, not evidence
that AP needs no judgement. The number to quote is not "the baseline gets
X%" -- it is "here is exactly what a rule engine already does, so here is
what the model has to be worth paying for."
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from typing import Any

from agent.messages import to_openai_dicts
from agent.schemas import Classification, Decision
from agent.tools import TERMINAL_TOOL
from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage
from langchain_core.outputs import ChatGeneration, ChatResult
from langchain_core.utils.function_calling import convert_to_openai_tool


@dataclass
class _View:
    """What the baseline has read so far, assembled from the message list."""

    invoice: dict | None = None
    po: dict | None = None
    receipts: list[dict] | None = None
    history: dict | None = None


def _dec(value: Any, default: str = "0") -> Decimal:
    try:
        return Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        return Decimal(default)


def _read_messages(messages: list[dict]) -> _View:
    """Reconstruct state from the transcript.

    Deliberately the same information channel the model has: if the baseline
    could reach around the message list it would not be a fair floor.
    """
    view = _View()
    pending: dict[str, str] = {}
    for message in messages:
        if message.get("role") == "assistant":
            for call in message.get("tool_calls") or []:
                function = call["function"] if isinstance(call, dict) else call.function
                name = function["name"] if isinstance(function, dict) else function.name
                call_id = call["id"] if isinstance(call, dict) else call.id
                pending[call_id] = name
        elif message.get("role") == "tool":
            name = pending.get(message.get("tool_call_id", ""), "")
            try:
                payload = json.loads(message.get("content", ""))
            except (json.JSONDecodeError, TypeError):
                continue
            if name == "get_invoice":
                view.invoice = payload
            elif name == "get_purchase_order":
                view.po = payload
            elif name == "get_goods_receipts":
                view.receipts = payload
            elif name == "get_vendor_history":
                view.history = payload
    return view


def _invoice_number(messages: list[dict]) -> str:
    """Pull the target invoice out of the user prompt, as a model would."""
    for message in messages:
        if message.get("role") == "user":
            for token in str(message.get("content", "")).replace(".", " ").split():
                if token.isdigit() and len(token) == 10 and token.startswith("51"):
                    return token
    return ""


def _resolve(view: _View) -> dict:
    """The three-way match itself. Returns submit_resolution arguments.

    Rule ORDER is the interesting part -- each rule assumes the ones above it
    did not fire. Structural problems (a line that does not exist, receipts
    that exceed the order) are checked before arithmetic, because you cannot
    meaningfully compare figures you do not trust.
    """
    invoice = view.invoice or {}
    po = view.po or {}
    receipts = view.receipts or []
    history = view.history or {}

    line = (invoice.get("items") or [{}])[0]
    inv_qty = _dec(line.get("MENGE"))
    inv_price = _dec(line.get("NETPR"))
    inv_item = line.get("BUZEI", "0001")
    ebelp = line.get("EBELP")
    number = invoice.get("BELNR", "")
    evidence = [f"INV {number} line {inv_item}: MENGE {inv_qty}, NETPR {inv_price}"]

    def out(classification, decision, reasoning, correction=None, escalation=None) -> dict:
        payload: dict[str, Any] = {
            "classification": str(classification),
            "decision": str(decision),
            "reasoning": reasoning,
            "evidence": evidence,
        }
        if correction is not None:
            payload["correction"] = correction
        if escalation is not None:
            payload["escalate_to"] = "AP_SUPERVISOR"
            payload["escalation_reason"] = escalation
        return payload

    # 1. Structural: does the PO line the invoice bills actually exist?
    po_items = {item.get("EBELP"): item for item in (po.get("items") or [])}
    if ebelp not in po_items:
        evidence.append(f"PO {po.get('EBELN')} has lines {sorted(po_items)}; invoice bills {ebelp}")
        return out(
            Classification.INSUFFICIENT_EVIDENCE,
            Decision.ESCALATE,
            f"The invoice bills PO line {ebelp}, which does not exist on the order.",
            escalation=f"Invoice references PO line {ebelp}; the order has {sorted(po_items)}.",
        )

    po_line = po_items[ebelp]
    po_qty = _dec(po_line.get("MENGE"))
    po_price = _dec(po_line.get("NETPR"))
    tolerance = po.get("ToleranceConfig") or {}
    price_tol = _dec(tolerance.get("PriceVariancePct"), "0")
    qty_tol = _dec(tolerance.get("QuantityVariancePct"), "0")
    evidence.append(f"PO {po.get('EBELN')} line {ebelp}: MENGE {po_qty}, NETPR {po_price}")
    evidence.append(f"ToleranceConfig: price {price_tol}%, quantity {qty_tol}%")

    # 2. Duplicate: same vendor reference already billed under another number.
    vendor_ref = invoice.get("XBLNR")
    earlier = sorted(
        row["BELNR"]
        for row in (history.get("InvoiceReferences") or [])
        if row.get("XBLNR") == vendor_ref and row.get("BELNR") != number
    )
    if earlier:
        evidence.append(f"Vendor history: XBLNR {vendor_ref} also billed as {earlier[0]}")
        return out(
            Classification.DUPLICATE_INVOICE,
            Decision.PROPOSE_CORRECTION,
            f"Vendor reference {vendor_ref} was already billed as {earlier[0]}.",
            correction={
                "correction_type": "REJECT_INVOICE",
                "invoice_number": number,
                "duplicate_of": earlier[0],
            },
        )

    # 3. Nothing received at all.
    matching = [gr for gr in receipts if gr.get("EBELP") == ebelp]
    if not matching:
        evidence.append(f"No goods receipts posted against PO line {ebelp}")
        return out(
            Classification.GOODS_RECEIPT_MISSING,
            Decision.ESCALATE,
            "Nothing has been received against this PO line, so there is no quantity to match.",
            escalation="No goods receipt exists; there is no received quantity to amend to.",
        )

    received = sum((_dec(gr.get("MENGE")) for gr in matching), Decimal(0))
    evidence.append(
        f"Receipts for line {ebelp}: {', '.join(gr.get('MBLNR', '?') for gr in matching)} "
        f"totalling {received}"
    )

    # 4. More arrived than was ordered -- authorised off-system, or posted twice?
    #    Either way it is not ours to decide.
    if received > po_qty:
        return out(
            Classification.INSUFFICIENT_EVIDENCE,
            Decision.ESCALATE,
            f"Receipts total {received} against an order of {po_qty}.",
            escalation=(
                f"Received quantity {received} exceeds ordered {po_qty}; cannot tell an "
                f"authorised over-delivery from a duplicated receipt."
            ),
        )

    # 5. Price outside tolerance.
    price_variance = (
        abs(inv_price - po_price) / po_price * 100 if po_price else Decimal(0)
    ).quantize(Decimal("0.01"))
    if price_variance > price_tol:
        return out(
            Classification.PRICE_VARIANCE_EXCEEDS_TOLERANCE,
            Decision.PROPOSE_CORRECTION,
            f"Invoiced {inv_price} against a PO price of {po_price}: "
            f"{price_variance}% over a {price_tol}% tolerance.",
            correction={
                "correction_type": "AMEND_INVOICE_PRICE",
                "invoice_number": number,
                "inv_item_number": inv_item,
                "from_price": str(inv_price),
                "to_price": str(po_price),
            },
        )

    # 6. Billed more than arrived, beyond tolerance.
    qty_variance = ((inv_qty - received) / received * 100 if received else Decimal(0)).quantize(
        Decimal("0.01")
    )
    if inv_qty > received and qty_variance > qty_tol:
        return out(
            Classification.QUANTITY_EXCEEDS_RECEIPT,
            Decision.PROPOSE_CORRECTION,
            f"Invoiced {inv_qty} against receipts of {received}: "
            f"{qty_variance}% over a {qty_tol}% tolerance.",
            correction={
                "correction_type": "AMEND_INVOICE_QUANTITY",
                "invoice_number": number,
                "inv_item_number": inv_item,
                "from_quantity": str(inv_qty),
                "to_quantity": str(received),
            },
        )

    # 7. A price wobble inside tolerance, on a blocked invoice: stale block.
    block = invoice.get("block_reason")
    if block and price_variance > 0:
        return out(
            Classification.PRICE_VARIANCE_WITHIN_TOLERANCE,
            Decision.RELEASE_BLOCK,
            f"Price variance {price_variance}% is inside the {price_tol}% tolerance "
            f"for this supplier, so the {block} block is stale.",
        )

    # 8. Less arrived than ordered, and only that much was billed.
    if received < po_qty and inv_qty == received:
        return out(
            Classification.PARTIAL_DELIVERY,
            Decision.POST_INVOICE,
            f"Ordered {po_qty}, received {received}, billed {inv_qty}. "
            f"The invoice matches the delivery.",
        )

    # 9. Everything agrees.
    return out(
        Classification.CLEAN,
        Decision.POST_INVOICE,
        f"Quantity {inv_qty} and price {inv_price} both match the order and the receipts.",
    )


#: The order the baseline gathers evidence in. Fixed, because a rule engine
#: has no reason to vary it -- which also makes its token cost constant.
PLAN = ("get_invoice", "get_purchase_order", "get_goods_receipts", "get_vendor_history")


def _already_proposed(messages: list[dict]) -> bool:
    for message in messages:
        for call in message.get("tool_calls") or []:
            function = call["function"] if isinstance(call, dict) else call.function
            name = function["name"] if isinstance(function, dict) else function.name
            if name == "propose_correction":
                return True
    return False


def _next_turn(messages: list[dict]) -> tuple[int, str, dict]:
    """(step, tool name, arguments) for the next turn, from the transcript alone."""
    view = _read_messages(messages)

    step = sum(1 for m in messages if m.get("role") == "assistant")
    name: str | None = PLAN[step] if step < len(PLAN) else None

    if name == "get_invoice":
        return step, name, {"invoice_number": _invoice_number(messages)}
    if name in ("get_purchase_order", "get_goods_receipts"):
        po = ((view.invoice or {}).get("items") or [{}])[0].get("EBELN", "")
        return step, name, {"po_number": po}
    if name == "get_vendor_history":
        return step, name, {"vendor_id": (view.invoice or {}).get("LIFNR", "")}

    resolution = _resolve(view)
    # Deciding to propose and actually proposing are different acts. An
    # agent that concludes PROPOSE_CORRECTION and then submits without
    # raising anything has left no proposal for a human to approve -- so
    # the baseline raises it, which also means the eval exercises the
    # write path rather than only the read path.
    if resolution["decision"] == "PROPOSE_CORRECTION" and not _already_proposed(messages):
        return (
            step,
            "propose_correction",
            {"payload": resolution["correction"], "agent_reasoning": resolution["reasoning"]},
        )
    return step, TERMINAL_TOOL, resolution


class BaselineChatModel(BaseChatModel):
    """The rule engine, as a chat model. Emits one tool call per turn, then submits."""

    @property
    def _llm_type(self) -> str:
        return "baseline-rules"

    def bind_tools(self, tools, **kwargs):
        # The rules already know the tool names; binding exists so the graph
        # can treat this exactly like a provider model.
        return self.bind(tools=[convert_to_openai_tool(t) for t in tools], **kwargs)

    def _generate(self, messages, stop=None, run_manager=None, **kwargs) -> ChatResult:
        step, name, arguments = _next_turn(to_openai_dicts(messages))
        reply = AIMessage(
            content="",
            id=f"baseline-{step}",
            tool_calls=[
                {
                    "name": name,
                    "args": arguments,
                    "id": f"call_baseline_{step}",
                    "type": "tool_call",
                }
            ],
            # A rule engine consumes no tokens. Reporting zero rather than
            # omitting usage keeps the cost column honest: free, not unknown.
            usage_metadata={"input_tokens": 0, "output_tokens": 0, "total_tokens": 0},
        )
        return ChatResult(generations=[ChatGeneration(message=reply)])
